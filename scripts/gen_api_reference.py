# The refusal sentences a client matches as they stand: a server sends these
# exact strings for these cases, whatever else its refusals say.
MATCHED_MSGIDS = (
    (
        "ALREADY_RUNNING_MSGID",
        "`spawn` refused `refused` because the session already runs; `args.pty` names its pty, and the "
        "client attaches to that instead.",
    ),
    (
        "PTY_GONE_MSGID",
        "A request refused `gone` because no such pty exists; `args.pty` names it. The client takes the "
        "pty as ended.",
    ),
    (
        "FOLDER_GONE_MSGID",
        "`fs.list` or `fs.walk` refused `gone` because the folder is not there. The tree drops its rows.",
    ),
)

FRAME_TAGS = (
    ("TAG_OUTPUT", "pty output, service to client; `stream` is the pty"),
    ("TAG_INPUT", "pty input, client to service; `stream` is the pty"),
    ("TAG_BLOB", "a chunk of a chunked message, either way; `stream` is the message id masked to 32 bits"),
)
FRAME_FLAGS = (
    ("FLAG_REDRAW", "output: part of a redraw (not counted, not acked)"),
    ("FLAG_REDRAW_END", "output: the redraw's last frame"),
)

_POWERS = {2**k - 1: f"2^{k} − 1" for k in (31, 32, 53, 64)}


def _num(value) -> str:
    if isinstance(value, float):
        return repr(value)
    if value in _POWERS:
        return _POWERS[value]
    if value >= 1024 * 1024 and value % (1024 * 1024) == 0:
        return f"{value:,} ({value // (1024 * 1024)} MiB)"
    return f"{value:,}"


def _code(text: str) -> str:
    """*text* as a code span safe inside a Markdown table cell."""
    return "`" + text.replace("|", "\\|") + "`"


def _choices(spec: p.Field) -> str:
    return ", ".join(_code(choice) for choice in sorted(spec.choices))


def _string_rules(spec: p.Field) -> list[str]:
    rules = []
    if spec.choices is not None:
        rules.append("one of " + _choices(spec))
        return rules
    low = spec.low or 0
    if spec.high is not None:
        high = _num(spec.high)
        rules.append(f"{low}–{high} characters" if low else f"at most {high} characters")
    elif low:
        rules.append(f"at least {low} characters")
    if spec.pattern is not None:
        rules.append("matching " + _code(spec.pattern.pattern))
    return rules


def describe(spec: p.Field) -> str:
    """One field's kind and bounds as a phrase for the table."""
    kind = spec.kind
    if kind == p.K_STR:
        return ", ".join(["string", *_string_rules(spec)])
    if kind == p.K_INT:
        return f"integer, {_num(spec.low)}–{_num(spec.high)}"
    if kind == p.K_NUM:
        return "finite number"
    if kind == p.K_BOOL:
        return "boolean"
    if kind == p.K_PATH:
        return f"absolute path, at most {_num(p.PATH_MAX)} characters, no NUL"
    if kind == p.K_HOME_PATH:
        return (
            f"absolute path, or `~` / `~/…` in the service's home, at most {_num(p.PATH_MAX)} characters"
        )
    if kind == p.K_URL:
        return f"http(s) URL, at most {_num(p.PATH_MAX)} characters"
    if kind == p.K_SCALAR:
        return f"string (at most {_num(p.ARG_TEXT_MAX)} characters), number, boolean or null"
    if kind == p.K_JSON:
        return "any JSON value (bounded: see [Free JSON](./index#free-json))"
    if kind == p.K_JSON_OBJECT:
        return "JSON object (bounded: see [Free JSON](./index#free-json))"
    if kind == p.K_LIST:
        size = _size("items", spec)
        item = describe(spec.item) if spec.item.kind != p.K_OBJ else "object (fields below)"
        return f"list{size} of: {item}"
    if kind == p.K_MAP:
        size = _size("entries", spec)
        key = f", keys matching {_code(spec.key.pattern)}" if spec.key is not None else ""
        item = describe(spec.item) if spec.item.kind != p.K_OBJ else "object (fields below)"
        return f"object{size}{key}, values: {item}"
    if kind == p.K_OBJ:
        one_of = f"; at least one of {', '.join(_code(n) for n in spec.one_of)}" if spec.one_of else ""
        return f"object (fields below{one_of})"
    raise AssertionError(f"unknown field kind {kind!r}")


def _size(noun: str, spec: p.Field) -> str:
    if spec.low and spec.high is not None:
        if spec.low == spec.high:
            return f" of exactly {_num(spec.high)} {noun}"
        return f" of {_num(spec.low)}–{_num(spec.high)} {noun}"
    if spec.high is not None:
        return f" of at most {_num(spec.high)} {noun}"
    if spec.low:
        return f" of at least {_num(spec.low)} {noun}"
    return ""


def _presence(spec: p.Field) -> str:
    words = ["required" if spec.required else "optional"]
    if spec.nullable:
        words.append("nullable")
    return ", ".join(words)


def field_rows(fields, prefix: str = "") -> list[str]:
    """The table rows of *fields*, nested objects flattened as `a.b` and
    list or map items as `a[].b` / `a.*.b`."""
    rows = []
    for name, spec in fields.items():
        path = prefix + name
        rows.append(f"| {_code(path)} | {describe(spec)} | {_presence(spec)} |")
        rows.extend(_nested_rows(spec, path))
    return rows


def _nested_rows(spec: p.Field, path: str) -> list[str]:
    if spec.kind == p.K_OBJ and spec.fields:
        return field_rows(spec.fields, path + ".")
    if spec.kind == p.K_LIST and spec.item.kind == p.K_OBJ:
        return field_rows(spec.item.fields or {}, path + "[].")
    if spec.kind == p.K_MAP and spec.item.kind == p.K_OBJ:
        return field_rows(spec.item.fields or {}, path + ".*.")
    return []


def fields_table(title: str, fields, one_of=()) -> list[str]:
    lines = [f"**{title}**"]
    if one_of:
        lines.append("")
        lines.append("At least one of " + ", ".join(_code(n) for n in one_of) + " must be present.")
    lines.append("")
    if not fields:
        lines.append("No fields.")
        lines.append("")
        return lines
    lines.append("| Field | Value | Presence |")
    lines.append("| --- | --- | --- |")
    lines.extend(field_rows(fields))
    lines.append("")
    return lines


def _peer(sender: str) -> str:
    return "client → service" if sender == p.CLIENT else "service → client"


def message_section(entry: p.MessageType) -> list[str]:
    lines = [f"### `{entry.name}`", "", entry.summary, ""]
    lines.extend([f"Family: `{entry.family}` · Level {entry.level}", ""])
    if entry.name in p.OPTIONAL_TYPES:
        lines.extend([f"*Optional for another client.* {p.OPTIONAL_TYPES[entry.name]}", ""])
    if entry.request is not None:
        lines.append("*Request*, client → service, answered by one response.")
        lines.append("")
        lines.extend(fields_table("Request fields", entry.request.fields, entry.request.one_of))
        lines.extend(fields_table("Reply fields (on `ok: true`)", entry.request.reply or {}))
    if entry.event is not None:
        lines.append(f"*Event*, {_peer(entry.event.sender)}, never answered.")
        lines.append("")
        lines.extend(fields_table("Event fields", entry.event.fields, entry.event.one_of))
    return lines


_SECTION_RE = re.compile(r"^    # -- (.*)$")
# A section comment's title is its text up to the first colon, with the
# references to the private design spec removed; these few read better
# under another name.
_TITLES = {
    "The e2e probe": "The debug probe",
    "The path picker's two": "The path picker",
}
_NAME_RE = re.compile(r'^        "([a-z][a-z0-9.-]*)",$')
_REF_RE = re.compile(r"\s*\((?:§|PR-|D\d)[^)]*\)|,?\s*(?:§[\d.]+|PR-[\d.a-z]+|D\d+)\b")


def sections(source_path: str) -> list[tuple[str, list[str]]]:
    """The table's sections, in order, from the `# -- title` comments in the
    source: each title (its references to the private design spec removed)
    with the names of the types under it. The source is read as text,
    since the comments are not in the module."""
    out: list[tuple[str, list[str]]] = []
    current: list[str] | None = None
    in_table = False
    with open(source_path, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.rstrip("\n")
            if line.startswith("_TABLE"):
                in_table = True
                continue
            if not in_table:
                continue
            if line.startswith(")"):
                break
            match = _SECTION_RE.match(line)
            if match:
                title = _REF_RE.sub("", match.group(1)).split(":")[0].strip().rstrip(",")
                title = title[0].upper() + title[1:]
                title = _TITLES.get(title, title)
                current = []
                out.append((title, current))
                continue
            match = _NAME_RE.match(line)
            if match and current is not None and match.group(1) in p.TYPES:
                current.append(match.group(1))
    return out


def _members(types: list[str]) -> str:
    return ", ".join(_code(name) for name in types) or "None of its own."


def _conformance_entry(heading: str, entry: p.Conformance, types: list[str]) -> list[str]:
    lines = [f"### {heading}", "", entry.summary, "", f"**Message types:** {_members(types)}", ""]
    if entry.state_keys:
        lines.extend([f"**State keys:** {_members(list(entry.state_keys))}", ""])
    if entry.status_fields:
        lines.extend([f"**`service.status` fields:** {_members(list(entry.status_fields))}", ""])
    if entry.notes:
        lines.append("**Also:**")
        lines.append("")
        lines.extend(f"- {note}" for note in entry.notes)
        lines.append("")
    return lines


def conformance_section() -> list[str]:
    """What a server must serve: the levels and the families with their
    members, which come from each type's `family` and `level`."""
    lines = [
        "## Conformance",
        "",
        "What a server must serve to be a server of this API; the rules are in "
        "[Implementing a server](./index#implementing-a-server). The levels build on each other. A "
        "family is optional at any level: a server serves one by listing its name in `caps`, and "
        "answers a type it doesn't serve `unknown`. Each message type below names its family and level.",
        "",
        "Every state key and `service.status` field belongs to one level or family. One that belongs to a "
        "family is emitted, read and written only by a server that lists the family. A client reads a key "
        "it never received as empty and a field it never received as unknown. Of `service.status`, only "
        "`version` and `protocol` are required.",
        "",
    ]
    core = [entry for entry in p.TYPES.values() if entry.family == p.FAMILY_CORE]
    for level, entry in p.CONFORMANCE_LEVELS.items():
        types = [kind.name for kind in core if kind.level == level]
        lines.extend(_conformance_entry(f"Level {level}: {entry.title}", entry, types))
    for family, entry in p.CONFORMANCE_FAMILIES.items():
        types = [kind.name for kind in p.TYPES.values() if kind.family == family]
        lines.extend(_conformance_entry(f"Family `{family}`: {entry.title}", entry, types))
    lines.extend(
        [
            "### Refusal sentences a client matches",
            "",
            "A client reads almost nothing from a refusal but its code. These three `msgid`s are the "
            "exceptions: send them exactly.",
            "",
            "| Name | Sentence | When |",
            "| --- | --- | --- |",
        ]
    )
    for name, meaning in MATCHED_MSGIDS:
        lines.append(f"| `{name}` | {_code(getattr(p, name))} | {meaning} |")
    lines.append("")
    return lines


def git_builders_section() -> list[str]:
    lines = [
        "## Git builders",
        "",
        "What `git.run`'s `builder` may name, with the keyword arguments its `args` takes. A client "
        "never sends a command line: the service builds it, and refuses arguments that don't fit "
        "(`invalid`). Every path is taken literally, never as a glob. Each command below runs as "
        "`git <command>` in `cwd`; the diff builders also pin git's prefix and quoting settings, so "
        "their output doesn't depend on the user's config.",
        "",
        "A `load` is what a diff is of: the string `unstaged`, `staged` or `branch` (which needs "
        "`parent_target`), `{\"show\": \"<ref>\"}` for a commit, or `{\"range\": \"<a>...<b>\"}` "
        "for a range, with exactly three dots.",
        "",
        "| Builder | Arguments | Runs |",
        "| --- | --- | --- |",
    ]
    for name, builder in p.GIT_BUILDERS.items():
        args = ", ".join(_code(arg) for arg in builder.args) or "none"
        lines.append(f"| {_code(name)} | {args} | {builder.runs.replace('|', chr(92) + '|')} |")
    lines.append("")
    return lines


def state_keys_section() -> list[str]:
    lines = [
        "## State keys",
        "",
        "What `state.get` and `state.set` may name. A `map` is a JSON object whose entries `entry` "
        "reads and writes one at a time, a `set` a list of distinct strings, a `list` an ordered list. "
        "A key that is not writable is refused `refused`, and an unknown one `gone`. Where a family of "
        "requests exists (`store.*`, `sandbox.*`, `notify.*`), use it: a direct write skips what the "
        "service does on top of it.",
        "",
        "| Key | Form | A client may write | Holds |",
        "| --- | --- | --- | --- |",
    ]
    for name, key in p.STATE_KEYS.items():
        lines.append(f"| {_code(name)} | {key.form} | {'yes' if key.writable else 'no'} | {key.summary} |")
    lines.extend(
        [
            "",
            "### Service settings",
            "",
            "The entries of `settings`. A value of another type is refused `refused`. So is a setting "
            "not listed here: appearance, geometry, sounds and the like belong to each client, which "
            "keeps its own.",
            "",
            "| Setting | Value | What it does |",
            "| --- | --- | --- |",
        ]
    )
    for name, setting in p.SERVICE_SETTINGS.items():
        lines.append(f"| {_code(name)} | {setting.kind} | {setting.summary} |")
    tools = ", ".join(_code(tool) for tool in p.SESSION_TOOLS)
    lines.extend(
        [
            "| `mcp_tool_<tool>` | boolean | Whether sessions are offered this session tool. |",
            "| `sandbox_tool_<tool>` | boolean | Whether sandboxed sessions are offered it by default. |",
            "",
            f"The session tools: {tools}.",
            "",
        ]
    )
    return lines


def render(source_path: str) -> str:
    lines = [HEADER]
    lines.append("## Numbers")
    lines.append("")
    lines.append("| Name | Value | Meaning |")
    lines.append("| --- | --- | --- |")
    for name, meaning in NUMBERS:
        lines.append(f"| `{name}` | {_num(getattr(p, name))} | {meaning} |")
    lines.append("")
    lines.append("## Binary frame tags and flags")
    lines.append("")
    lines.append("| Name | Value | Meaning |")
    lines.append("| --- | --- | --- |")
    for name, meaning in FRAME_TAGS + FRAME_FLAGS:
        lines.append(f"| `{name}` | `0x{getattr(p, name):02x}` | {meaning} |")
    lines.append("")
    lines.append("## Enumerations")
    lines.append("")
    for name, meaning in ENUMERATIONS:
        values = getattr(p, name)
        ordered = list(values) if isinstance(values, tuple) else sorted(values)
        lines.append(f"- `{name}`: {meaning}  ")
        lines.append("  " + ", ".join(_code(v) for v in ordered))
    lines.append("")
    lines.extend(conformance_section())
    lines.append("## Message types")
    lines.append("")
    lines.append(
        "A *request* carries an integer `id` and is answered by exactly one response; "
        "an *event* carries none and is never answered. Fields a type does not list "
        "are dropped by the receiver. `required` fields must be present; `nullable` "
        "ones may be `null`."
    )
    lines.append("")
    table = sections(source_path)
    listed = {name for _, names in table for name in names}
    missing = [name for name in p.type_names() if name not in listed]
    if missing:
        table.append(("Other", missing))
    for title, names in table:
        lines.append(f"## {title}")
        lines.append("")
        for name in names:
            lines.extend(message_section(p.TYPES[name]))
    lines.extend(git_builders_section())
    lines.extend(state_keys_section())
    return "\n".join(lines).rstrip("\n") + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed document is stale")
    parser.add_argument("--stdout", action="store_true", help="print the document instead of writing it")
    args = parser.parse_args(argv)
    text = render(os.path.join(ROOT, SOURCE))
    target = os.path.join(ROOT, OUTPUT)
    if args.stdout:
        sys.stdout.write(text)
        return 0
    if args.check:
        try:
            with open(target, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            current = ""
        if current != text:
            print(f"{OUTPUT} is stale: run python3 scripts/gen_api_reference.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8") as handle:
        handle.write(text)
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
