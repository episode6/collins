    ("MIN_PROTOCOL", "The oldest protocol this build still speaks."),
    ("MAX_FRAME", "The largest frame either peer sends, in bytes; larger transfers are chunked."),
    ("MAX_INCOMING", "The largest frame either peer accepts, in bytes."),
    ("MAX_PAYLOAD", "The most payload bytes one binary frame carries (the frame less its header)."),
